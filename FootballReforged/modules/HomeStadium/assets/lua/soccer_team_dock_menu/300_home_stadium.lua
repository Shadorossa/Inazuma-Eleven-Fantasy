    local h = hint_y + L.HINT_H / 2 + L.BOTTOM - L.TOP
    return il, it, iw, ih, sel_y, hint_y, h, iw + 2 * L.PAD
  end

  local function quad(idx, sprite, x, y, w, h)
    M(K.LAYER_SCALE, K.PLATE, w / L.QUAD, h / L.QUAD, 1, idx)
    M(K.SPRITE, K.PLATE, sprite[1], sprite[2], K.QUAD_NODE, 0, idx)
    M(K.LAYER_POS, K.PLATE, x, -y, 0, idx)
    M(K.DRAW_PRIORITY, K.PLATE, idx, PRIORITY_OF[idx] or L.PRIORITY.OVER, true)
    M(K.VISIBLE, K.PLATE, idx, true)
  end

  local function hide_quad(idx)
