    M(K.DRAW_PRIORITY, K.FRAME, 0, L.PRIORITY.FRAME, true)
  end

  -- the selector's drawing for entry i of rows ({ map, name }); current = the team's home stadium
  local function draw(rows, i, current)
    local il, it, iw, ih, sel_y, hint_y, h, ww = geometry()
    local st = rows[i]
    quad(Q_WINDOW, K.SPRITE_WINDOW, L.CX, L.TOP + h / 2, ww, h)
    -- the name plate: the picture's width, the arrows inside its ends, the name centred in the room between them
    quad(Q_PLATE, K.SPRITE_PLATE, L.CX, sel_y, iw, L.SEL_H)
    local ax = iw / 2 - L.ARROW_IN - L.ARROW_W / 2
    S.arrows = {y = sel_y, [Q_ARROW_L] = L.CX - ax, [Q_ARROW_R] = L.CX + ax}
    -- active arrows; dim only where the list ends (no wrap-around: nothing before the first, nothing after the last)
    quad(Q_ARROW_L, i > 1 and K.SPRITE_ARROW_L or K.SPRITE_ARROW_L_DIM, L.CX - ax, sel_y, L.ARROW_W, L.ARROW_H)
    quad(Q_ARROW_R, i < #rows and K.SPRITE_ARROW_R or K.SPRITE_ARROW_R_DIM, L.CX + ax, sel_y, L.ARROW_W, L.ARROW_H)
    label(T_HINT, text_of(K.TEXT_HINT), L.CX, hint_y, L.HINT_SCALE)
    local room = 2 * (ax - L.ARROW_W / 2 - L.NAME_ROOM)
    local mark = st.map == current
    local cx = L.CX
    if mark then                          -- the check takes the room's left part; the name centres in the rest
      room = room - L.CHECK - L.CHECK_GAP
      cx = L.CX + (L.CHECK + L.CHECK_GAP) / 2
    end
    local w = label(T_NAME, st.name, cx, sel_y, L.NAME_SCALE, room, L.NAME_MIN, L.NAME_STYLE)
    if mark then
      quad(Q_CHECK, K.SPRITE_CHECK, cx - math.min(w, room) / 2 - L.CHECK_GAP - L.CHECK / 2, sel_y, L.CHECK, L.CHECK)
    else
      hide_quad(Q_CHECK)
    end
    -- the picture (none for «Sin estadio local»: hidden)
    local ok = false
    if is_open(K.FRAME) then
      place_frame()
      ok = st.map ~= 0 and picture(K.FRAME, st.map) == true
      M(K.VISIBLE, K.FRAME, 0, ok)
    end
    hide_quad(Q_SPARE)
  end

  -- the arrow's press feedback, started by a move (dir -1 left / 1 right): the arrow of that side slides NUDGE px
  -- that way and grows by PULSE, then comes back (a sine over NUDGE_FRAMES frames). nudge_step advances it one frame
  -- while one runs; draw() has put the arrows at their places (S.arrows).
  local function nudge_start(dir)
    S.nudge = {q = dir < 0 and Q_ARROW_L or Q_ARROW_R, dir = dir, t = 0}
  end

  local function nudge_step()
    local n, a = S.nudge, S.arrows
    if n == nil or a == nil then return end
    n.t = n.t + 1
    local k = n.t < L.NUDGE_FRAMES and math.sin(math.pi * n.t / L.NUDGE_FRAMES) or 0
    local s = 1 + L.PULSE * k
    M(K.LAYER_SCALE, K.PLATE, L.ARROW_W * s / L.QUAD, L.ARROW_H * s / L.QUAD, 1, n.q)
    M(K.LAYER_POS, K.PLATE, a[n.q] + n.dir * L.NUDGE * k, -a.y, 0, n.q)
    if k == 0 then S.nudge = nil end
  end

  local function open_layers(on)
    for i = 0, QUADS - 1 do
      if on then M(K.OPEN_LAYER, K.PLATE, i) else M(K.CLOSE_LAYER, K.PLATE, i) end
    end
    for i = 0, TEXTS - 1 do
      if on then M(K.OPEN_LAYER, K.LABEL, i) else M(K.CLOSE_LAYER, K.LABEL, i) end
    end
    if on then M(K.OPEN_LAYER, K.FRAME, 0) else M(K.CLOSE_LAYER, K.FRAME, 0) end
  end

  -- the pad and the keys held this frame
  local function buttons()
    local ok, held = pcall(funcLuaCommand, K.PAD)
    held = (ok and type(held) == "number" and held >= 0) and held or 0
    local function pad(m) return math.floor(held / m) % 2 == 1 end
    local function key(vk)
      local okk, v = pcall(funcLuaCommand, K.KEY, vk)
      return okk and v == true
    end
    return {
      left = pad(PAD.LEFT) or key(VK.LEFT), right = pad(PAD.RIGHT) or key(VK.RIGHT),
      l1 = pad(PAD.L1) or key(VK.PRIOR), r1 = pad(PAD.R1) or key(VK.NEXT),
      ok = pad(PAD.A) or key(VK.ENTER),
      back = pad(PAD.B) or pad(PAD.BACK) or key(VK.ESC) or key(VK.BACKSPACE),
    }
  end

  -- the dock's green focus cursor (cmn05_01_cursor): it follows the focused item's «cursor» locator (the button's,
  -- traced by the retail focus shift), so it is untraced and hidden while the selector is open, back on close
  local function dock_cursor(a1, on)
    if a1 == K.BUTTON then
      M(VRFW_Cmd.SET_LAYER_ATTACH_LOCATOR_TRACE, K.BUTTON, 0, 3313461902 --[[cursor]], on)
    end
    M(VRFW_Cmd.SET_LAYER_VISIBLE, K.CURSOR, 0, on, K.MENU)
    M(VRFW_Cmd.SET_LAYER_VISIBLE, K.CURSOR, 0, on)
  end

  local function pick(a1)
    local set = shown_set()
    local function back()
      open_layers(false)
      dock_cursor(a1, true)
      funcLuaMenuCommand(1558704558, K.MENU, true)
      funcLuaMenuCommand(VRFW_Cmd.SET_ENABLE_CTRL_FOCUS, a1, true)
      pcall(dress, "pick")       -- the button picture follows the pick
    end
    if foreign_stadium() ~= nil then
      H.log("dock: the team on screen is not one of the player's: its own stadium stays")
      pcall(funcLuaCommand, K.SOUND, K.SE_NO)
      back()
      return
    end
    if type(set) ~= "number" or set < 0 then
      H.log("dock: no team on screen")
      pcall(funcLuaCommand, K.SOUND, K.SE_NO)
      back()
      return
    end
    local current = H.get(set)
    local rows, sel = { { map = 0, name = text_of(K.TEXT_NONE) } }, 1
    for _, st in ipairs(H.owned()) do
      rows[#rows + 1] = st
      if st.map == current then sel = #rows end
    end
    S.set = set
    H.log("team", set, "selector:", #rows - 1, "owned stadium(s), current", string.format("0x%08X", current))
    funcLuaMenuCommand(1558704558, K.MENU, false)
    dock_cursor(a1, false)
    open_layers(true)
    wait(function() return is_open(K.FRAME) end)
    local il, it = geometry()
    frame_position(il, it)
    pcall(funcLuaCommand, K.SOUND, K.SE_GO)
    draw(rows, sel, current)
    -- input: edges after a release (the press that opened it does not count), LEFT / RIGHT repeat while held
    local prev = {left = true, right = true, l1 = true, r1 = true, ok = true, back = true}
    local guard, hold, hold_dir = L.GUARD, 0, nil
    S.nudge = nil
    while true do
      coroutine.yield()
      nudge_step()
      local b = buttons()
      local p = prev
      local function edge(k) return b[k] and not p[k] end
      prev = b
      if guard > 0 then
        guard = guard - 1
      elseif edge("back") then
        pcall(funcLuaCommand, K.SOUND, K.SE_BACK)
        break
      elseif edge("ok") then
        local map = rows[sel].map
        if H.set(set, map) then
          pcall(funcLuaCommand, K.SOUND, K.SE_GO)
          H.log("team", set, "home stadium", string.format("0x%08X", map))
        else
          pcall(funcLuaCommand, K.SOUND, K.SE_NO)
        end
        break
      else
        local dir = (b.left and -1) or (b.right and 1) or nil
        local step = nil
        if dir ~= nil then
          if dir ~= hold_dir then
            hold_dir, hold, step = dir, 0, dir
          else
            hold = hold + 1
            if hold >= L.REPEAT_WAIT and (hold - L.REPEAT_WAIT) % L.REPEAT_EVERY == 0 then step = dir end
          end
        else
          hold_dir, hold = nil, 0
          step = (edge("l1") and -1) or (edge("r1") and 1) or nil
        end
        if step ~= nil and sel + step >= 1 and sel + step <= #rows then
          sel = sel + step
          pcall(funcLuaCommand, K.SOUND, K.SE_MOVE)
          draw(rows, sel, current)
          nudge_start(step)
        end
      end
    end
    S.nudge = nil
    -- the press that closed the selector stays with it: the dock's control comes back once that key is released (its
    -- own BACK would close «Plantilla de equipo» on the same press)
    open_layers(false)
    wait(function()
      local b = buttons()
      return not (b.back or b.ok)
    end)
    coroutine.yield()
    back()
  end

  -- the selector starts in a coroutine of this file (button decide, OnEnter, OnDecideFocus), one at a time
  local function start(a1, why)
    if S.co ~= nil then return true end
    H.log("dock: selector requested by", why)
    S.from = a1
    S.co = coroutine.create(function() pick(a1) end)
    return true
  end

  local function tick()
    if S.co == nil then return end
    local ok, err = coroutine.resume(S.co)
    if not ok then
      H.log("dock: selector error", tostring(err))
      pcall(open_layers, false)
      pcall(dock_cursor, S.from, true)
      pcall(funcLuaMenuCommand, 1558704558, K.MENU, true)
      pcall(funcLuaMenuCommand, VRFW_Cmd.SET_ENABLE_CTRL_FOCUS, S.from, true)
    end
    if not ok or coroutine.status(S.co) == "dead" then
      S.co = nil
    end
  end

  -- the button (BetterUI): its step drives the picture and the selector; its decide starts the selector
  local install                     -- defined below (the button's step() may call it first)
  if type(BetterUI) == "table" and type(BetterUI.AddDockButton) == "function" then
    button = BetterUI.AddDockButton({
      id = "home_stadium.dock", layer = K.BUTTON, help = K.TEXT_HELP, column = "panel",
      mesh = { node = K.BOX, x = -403, y = -24 }, center = { x = -198, y = -46.5 },   -- the box + title's centre
      step = function()             -- drives the selector's coroutine only (nothing to do while it is closed)
        if not S.installed then install("first button step") end
        S.steps = S.steps + 1
        tick()
      end,
    }) == true
  end

  -- the dock's callbacks, wrapped (each wrapper calls what it replaced). Installed LATE, once every patch of the dock
  -- has loaded: a later root (Pachangas' pachanga_dock) redefines the dock's functions from the retail text, which
  -- dropped wrappers made at this file's load (1.1.x: none of them ever ran). install() runs at the framework host's
  -- first callback (@edit) or, with BetterUI, at the button's first step(), whichever comes first.
  local wraps = {}
  local function wrap(name, make)
    wraps[#wraps + 1] = {name, make}
  end
  install = function(why)
    if S.installed then return end
    S.installed = true
    local done = {}
    for _, w in ipairs(wraps) do
      local prev = rawget(_ENV, w[1])
      if type(prev) == "function" then
        rawset(_ENV, w[1], w[2](prev))
        done[#done + 1] = w[1]
      end
    end
    H.log("dock: callbacks wrapped (" .. tostring(why) .. "):", table.concat(done, ", "))
    pcall(idle_look, "install")
    pcall(dress, "install")
    pcall(add_row)
  end

  wrap("OnSetupLayer", function(prev)
    return function(a1, a2, ...)
      if a1 == K.LIST and a2 == 0 then
        pcall(add_row)
      end
      local r = table.pack(prev(a1, a2, ...))
      if button and a1 == K.BUTTON then
        -- as the retail FORMACIÓN box's setup: its draw / text priorities, one item
        pcall(funcLuaMenuCommand, VRFW_Cmd.SET_DRAW_PRIORITY, a1, a2 or 0, 453)
        pcall(funcLuaMenuCommand, VRFW_Cmd.SET_MENU_TEXT_PRIORITY, a1, a2 or 0, K.NAME_NODE, 454)
        pcall(funcLuaMenuCommand, 3252599449, a1, 1)
        pcall(dress, "setup " .. tostring(a1))
      end
      return table.unpack(r, 1, r.n)
    end
  end)

  -- the button on its events: its layer opening (unfocused look, text), the dock's team switch
  wrap("OnOpenLayer", function(prev)
    return function(a1, a2, ...)
      local r = table.pack(prev(a1, a2, ...))
      if a1 == K.BUTTON then
        pcall(idle_look, "open")
        pcall(dress, "open " .. tostring(a1))
      end
      return table.unpack(r, 1, r.n)
    end
  end)

  wrap("UpdateTeamDockNo", function(prev)
    return function(...)
      local r = table.pack(prev(...))
      if button then
        pcall(dress, "team switch")
      end
      return table.unpack(r, 1, r.n)
    end
  end)

  -- the selector without the button (the list row): resumed by the dock's Step, unless the button's step drives it
  wrap("Step", function(prev)
    return function(...)
      local r = table.pack(prev(...))
      if not (button and S.steps > 0) then
        pcall(tick)
      end
      return table.unpack(r, 1, r.n)
    end
  end)

  wrap("OnEnter", function(prev)
    return function(a1, a2, ...)
      if a1 == K.BUTTON then
        start(a1, "OnEnter")
        return 1
      end
      return prev(a1, a2, ...)
    end
  end)

  wrap("OnDecideFocus", function(prev)
    return function(a1, a2, ...)
      if a1 == K.BUTTON then
        start(a1, "OnDecideFocus")
        return
      end
      if a1 == K.LIST and type(a2) == "number" and S.kinds ~= nil and S.kinds[a2 + 1] == K.KIND then
        start(a1, "the list row")
        return
      end
      return prev(a1, a2, ...)
    end
  end)

  if VRFW_Host ~= nil then
    VRFW_Host.on("soccer_team_dock_menu", "@edit", { id = "home_stadium.dock_install", fn = function() install("host") end })
  end
end
