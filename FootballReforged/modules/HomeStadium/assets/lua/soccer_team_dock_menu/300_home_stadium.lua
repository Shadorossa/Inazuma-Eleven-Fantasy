  end

  -- a text centred on cx at the line y, shrunk to fit `room` px (down to `min` x scale; past that it overflows evenly
  -- on both sides). A centred style centres the text on its rectangle: the rectangle's centre goes on cx. Returns the
  -- drawn width.
  local function label(idx, s, cx, y, scale, room, min, style)
    for _, m in ipairs(K.TEXT_MESHES) do M(K.MESH_VISIBLE, K.LABEL, m, false, idx) end
    if style ~= nil then M(K.TEXT_STYLE, K.LABEL, idx, K.TEXT_NODE, style) end
    M(K.LAYER_SCALE, K.LABEL, 1, 1, 1, idx)
    M(K.TEXT_SET, K.LABEL, K.TEXT_NODE, s, idx)
    local w = M(K.TEXT_WIDTH, K.LABEL, idx, K.TEXT_NODE)
    w = (type(w) == "number" and w > 0) and w or 16 * #s
    if room ~= nil and w * scale > room then scale = math.max(min or scale, room / w) end
    M(K.LAYER_SCALE, K.LABEL, scale, scale, 1, idx)
    local left
    if style ~= nil then
      left = cx - (L.LABEL_LEFT + L.TEXT_BOX_W / 2) * scale      -- the rectangle's centre on cx
    else
      left = cx - w * scale / 2 - L.LABEL_LEFT * scale           -- a left-aligned text: its measured width
    end
    M(K.LAYER_POS, K.LABEL, left, -y - L.LABEL_MID_Y * scale, 0, idx)
    M(K.VISIBLE, K.LABEL, idx, s ~= "")
    return w * scale
  end

