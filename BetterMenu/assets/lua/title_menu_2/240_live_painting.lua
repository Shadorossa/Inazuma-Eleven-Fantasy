-- BetterMenu (mod better_menu, prefix BetterMenu): the live painting of the main menu over the clubhouse
-- (title_menu_2; docs/game/mods/better-menu.md §37). In the Crónica shot the big painting under the staircase shows the
-- Chronicle top menu in motion: the framework fits the quad layer better_menu_live_painting to the painting's picture
-- and fades it in and out with the shot ([[VRFW.MenuSceneScreen]] chronicle_painting in
-- content\menu_scenes\clubhouse.toml); this script plays its flipbook: the frames better_menu_live_painting_00 .. of the
-- layer's own atlas (content\images\menu\20_cmn\better_menu_live_painting.toml, GENERATED by
-- research/scripts/better_menu_live_painting_build.py), one every FRAME_STEPS game frames, while the scene's screens
-- run. No engine call at load time.
BetterMenu = type(BetterMenu) == "table" and BetterMenu or {}
if BetterMenu.LivePainting == nil then
  local function Crc(s)
    local crc = 0xFFFFFFFF
    for i = 1, #s do
      crc = bit32.bxor(crc, string.byte(s, i))
      for _ = 1, 8 do
        if bit32.band(crc, 1) ~= 0 then
          crc = bit32.bxor(bit32.rshift(crc, 1), 0xEDB88320)
        else
          crc = bit32.rshift(crc, 1)
        end
      end
    end
    return bit32.bxor(crc, 0xFFFFFFFF)
  end

  local Painting = {
    ID = "better_menu.live_painting",
    LOG = Crc("CMND_EVT_LOG"),
    LAYER = Crc("better_menu_live_painting"),
    ATLAS = Crc("#/menu/20_cmn/cmn01/better_menu_live_painting/better_menu_live_painting.g4tx"),
    SLOT = Crc("icon_new01"),                      -- the quad's sprite node (the retail badge)
    FRAME_PREFIX = "better_menu_live_painting_",
    FRAMES = 40,                                   -- the generated loop: 40 frames of 4 s
    FRAME_STEPS = 6,                               -- game frames per picture (60 fps: 10 pictures a second)
    SCREEN = "chronicle_painting",
    -- engine
    SPRITE = 558735651,                            -- (layer, texture, sprite, old sprite, 0, instance)
    LAYER_NUM = 1175615627,                        -- (layer) -> instances
    SCREENS = Crc("CMND_VRFW_MENU_SCENE_SCREENS"), -- (key) -> "" | { n, [i] = { name, on, … } }
    SCENE_FOR = Crc("CMND_VRFW_MENU_SCENE_FOR"),   -- (menu) -> key | ""
    PARAM_HAS = 2947612279,                         -- (key) -> set
  }
  local state = { has_layer = nil, key = nil, steps = 0, frame = -1, playing = false, sprites = nil }

  local function Log(...)
    pcall(funcLuaCommand, Painting.LOG, "better_menu", "live_painting", ...)
  end

  local function M(...)
    local r = table.pack(pcall(funcLuaMenuCommand, ...))
    if not r[1] then return nil end
    return table.unpack(r, 2, r.n)
  end

  local function F(...)
    local r = table.pack(pcall(funcLuaCommand, ...))
    if not r[1] then return nil end
    return table.unpack(r, 2, r.n)
  end

  local function HasLayer()
    if state.has_layer == nil then
      local n = M(Painting.LAYER_NUM, Painting.LAYER)
      state.has_layer = type(n) == "number" and n > 0
      if not state.has_layer then Log("no layer better_menu_live_painting in this menu: no live painting") end
    end
    return state.has_layer
  end

  -- the screen's answer: shown now (its shot on, or fading out)
  local function ScreenActive()
    if state.key == nil then
      local k = F(Painting.SCENE_FOR, "title_menu_2")
      state.key = type(k) == "string" and k or ""
    end
    if state.key == "" then return false end
    local r = F(Painting.SCREENS, state.key)
    if type(r) ~= "table" then return false end
    for i = 1, tonumber(r.n) or 0 do
      local e = r[i]
      if type(e) == "table" and e.name == Painting.SCREEN then
        -- on, or fading out (the framework's fade after the shot left)
        if e.on == 1 then state.off_steps = 0 return true end
        state.off_steps = (state.off_steps or 0) + Painting.FRAME_STEPS
        return state.off_steps * 1000 / 60 <= (tonumber(e.fade_ms) or 0)
      end
    end
    return false
  end

  local function Step()
    if not (type(VRFW_MenuSceneIsUp) == "function" and VRFW_MenuSceneIsUp()) or not HasLayer() then return end
    state.steps = state.steps + 1
    if state.steps % Painting.FRAME_STEPS ~= 0 then return end
    local active = ScreenActive()
    if active ~= state.playing then
      state.playing = active
      Log(active and "playing" or "stopped", "frame", state.frame)
    end
    if not active then return end
    if state.sprites == nil then
      state.sprites = {}
      for i = 0, Painting.FRAMES - 1 do state.sprites[i] = Crc(string.format("%s%02d", Painting.FRAME_PREFIX, i)) end
    end
    state.frame = (state.frame + 1) % Painting.FRAMES
    M(Painting.SPRITE, Painting.LAYER, Painting.ATLAS, state.sprites[state.frame], Painting.SLOT, 0, 0)
  end

  BetterMenu.LivePainting = { Step = Step }

  if VRFW_Host ~= nil then
    VRFW_Host.on("title_menu_2", "OnInit", {
      id = Painting.ID .. ".init",
      phase = "before",
      fn = function()
        state.has_layer, state.key, state.steps, state.frame, state.playing, state.off_steps = nil, nil, 0, -1, false, 0
      end,
    })
    VRFW_Host.on("title_menu_2", "Step", {
      id = Painting.ID .. ".step",
      phase = "after",
      priority = 10,
      fn = function()
        local ok, err = pcall(Step)
        if not ok then Log("error", tostring(err)) end
      end,
    })
  end
end
