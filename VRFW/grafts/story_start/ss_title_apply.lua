-- Story-complete start of the VR-Framework (docs/framework/save-slots.md §7, docs/game/modes/story-complete-start.md
-- §10; graft story_start, mod vr_framework since 2026-10-08, before that Inazuma Fantasy's), appended to
-- title_menu_inc (included by title_menu AND title_menu_2). When title_menu_2 opens on a player slot whose marker is
-- «pending» (the player answered yes on the slot screen; the save part answers only for player slots but the locked
-- one), the avatar exists and the story phase is still 0, the post-story state is applied ONCE, from OnInit (the
-- title_menu_2 host handler of ss_title2.lua, or the wrapper below), with retail commands only:
--   story flags / byte flags / help / quests / search words -> story team set (kit, emblem, formation)
--   -> story roster at Lv 50 (story bank) -> the 15 scouts joined -> shirt numbers -> normal copies (Chronicle / VS)
--   -> story matches won -> story trophies (no Steam: notify = false + loader guard) -> story end walk
--   -> phase 9/80 (loader) -> the story-clear flag b0:1 LAST -> autosave.
-- The save part turns the marker «done» once the slot's SAVED file shows the story cleared; until then a game that quit
-- before saving is simply applied again (it starts from the fresh new game). The phase goes to BOTH phase records
-- (the saved m_Parmanent and the live copy; §11: the loader of 28/09 wrote only the live one, which the save drops):
-- a pending slot with b0:1 on and saved phase 0 gets the phase only (REPAIR), never the roster twice. Nothing runs at load time: funcLuaCommand
-- is registered after the chunk (docs/game/engine/lua-patches.md), so the work hangs on OnInit (wrapper below).
-- Data: SS_DATA, generated by research/scripts/story_start_build.py (ss_data.lua).
