local VRFW_STS_ran = false        -- once per VM (the OnInit chain may be wrapped twice)

local function VRFW_STS_Call(cmd, ...)
  local r = table.pack(pcall(funcLuaCommand, cmd, ...))
  if not r[1] then
    return nil, r[2]
  end
  return table.unpack(r, 2, r.n)
end

local function VRFW_STS_Log(...)
  VRFW_STS_Call(VRFW_STS.LOG, "story_start", ...)
end

-- one section of the apply: never stops the others; returns the number of calls made
local function VRFW_STS_Section(name, fn)
  local ok, n = pcall(fn)
  if not ok then
    VRFW_STS_Log("section FAILED", name, tostring(n))
    return 0
  end
  VRFW_STS_Log("section", name, tostring(n))
  return n or 0
end

local function VRFW_STS_Apply()
  local D = SS_DATA
  local F = funcLuaCommand
  VRFW_STS_Section("flags", function()
    local n = 0
    for i = 1, #D.BITS - 1 do        -- the last entry (b0:1 story clear) is set at the very end
      F(VRFW_STS.SET_BIT, D.BITS[i], true)
      n = n + 1
    end
    for _, h in ipairs(D.BITS_OFF) do
      F(VRFW_STS.SET_BIT, h, false)
    end
    for _, b in ipairs(D.BYTES) do
      F(VRFW_STS.SET_BYTE, b[1], b[2])
      n = n + 1
    end
    return n
  end)
  VRFW_STS_Section("help/quests/words", function()
    local n = 0
    for _, h in ipairs(D.HELP) do
      if F(VRFW_STS.HELP_GET, h) == false then
        F(VRFW_STS.HELP_OPEN, h)
      end
      F(VRFW_STS.HELP_SET, h)
      n = n + 1
    end
    for _, q in ipairs(D.QUESTS) do
      F(VRFW_STS.QUEST, q[1], q[2])
      n = n + 1
    end
    for _, w in ipairs(D.WORDS) do
      F(VRFW_STS.WORD, w)
      n = n + 1
    end
    return n
  end)
  VRFW_STS_Section("team set + kit", function()
    local n = 0
    for _, t in ipairs(D.TEAM_INFO) do
      F(VRFW_STS.TEAM_INFO, t[1], t[2], t[3])
      n = n + 1
    end
    for _, it in ipairs(D.ITEMS) do         -- the story kit (SET_TEAM_SET_INFO kind 5 needs the owned uniform)
      if F(VRFW_STS.ITEM_CAN, it[1], it[2]) then
        F(VRFW_STS.ITEM_ADD, it[1], it[2])
        n = n + 1
      end
    end
    return n
  end)
  VRFW_STS_Section("story roster", function()
    local n = 0
    for _, a in ipairs(D.ADDS) do
      -- prog_common AddPartyCore: CMND_ADD_PARTY(param, lv, a4, a6, 0, 0, story, flag2, flag3, set, slot, n3, 0,
      -- false, false, flag4, 0, false, flag5)
      F(VRFW_STS.ADD_PARTY, a[1], D.LEVEL, a[2], a[3], 0, 0, a[4], a[5], a[6], a[7], a[8], a[9], 0, false, false, a[10], 0, false, a[11])
      n = n + 1
    end
    return n
  end)
  VRFW_STS_Section("scouts", function()
    local n = 0
    for _, s in ipairs(D.SCOUTS) do
      -- the retail join (rpg_select_scout_chara_menu ConfirmCharaExec + the recipe's DbgPhCmd_4_90): temp chara,
      -- ADD_PARTY into the story bank (source 2 = scout), join flag, join status 6; the developers' 5 go to set 0
      local tmp = F(VRFW_STS.TEMP_CHARA, s[1], D.LEVEL)
      if type(tmp) ~= "number" then
        tmp = 0
      end
      F(VRFW_STS.ADD_PARTY, s[1], D.LEVEL, false, false, 0, tmp, true, false, false, s[4] and 0 or 16, 255, 255, 0, false, false, false, 2)
      F(VRFW_STS.CLEAR_CAT, 8)
      F(VRFW_STS.SET_BIT, s[3], true)
      local ok, idx = F(VRFW_STS.SCOUT_IDX, s[2], 7)
      if ok and type(idx) == "number" then
        F(VRFW_STS.SCOUT_JOIN, idx, 6)
      end
      n = n + 1
    end
    return n
  end)
  VRFW_STS_Section("team set info", function()
    local n = 0
    for _, t in ipairs(D.TEAM_SET) do
      F(VRFW_STS.TEAM_SET, table.unpack(t))
      n = n + 1
    end
    return n
  end)
  VRFW_STS_Section("normal copies", function()
    local n = 0
    for _, p in ipairs(D.NORMAL) do          -- normal bank, no team set (logical 16): Chronicle / VS (decision 1)
      F(VRFW_STS.ADD_PARTY, p, D.NORMAL_LEVEL, false, false, 0, 0, false, false, false, 16, 255, 255, 0, false, false, false, 0, false, false)
      n = n + 1
    end
    return n
  end)
  VRFW_STS_Section("story matches", function()
    for _, g in ipairs(D.GAMES) do
      F(VRFW_STS.GAME_CLEAR, g, 1, true)
    end
    return #D.GAMES
  end)
  VRFW_STS_Section("trophies", function()
    for _, t in ipairs(D.TROPHIES) do
      F(VRFW_STS.TROPHY, t[1], t[2], false)     -- notify = false: no Steam (the loader guard drops the rest)
    end
    return #D.TROPHIES
  end)
  VRFW_STS_Section("story end", function()
    F(VRFW_STS.STORY_END)            -- 0x311C0E04 = c09 RunCmd_Phase24 (0xE63730)
    F(VRFW_STS.UPDATE_PARTY)
    return 2
  end)
  local old, new = VRFW_STS_Call(VRFW_STS.PHASE, D.PHASE[1], D.PHASE[2])
  VRFW_STS_Log("phase", tostring(old), "->", tostring(new))
  F(VRFW_STS.SET_BIT, D.BITS[#D.BITS], true)      -- b0:1 story clear, last
end

-- title_menu_2 OnInit (before the menu's own OnInit): apply when the marker is pending
function VRFW_STS_OnTitle()
  if VRFW_STS_ran or rawget(_G, "StartTitleMenu2_Coroutine") == nil then
    return                           -- once per VM; only in title_menu_2 (not the press-start title_menu)
  end
  VRFW_STS_ran = true
  -- phase = the SAVED phase record (m_Parmanent: what the file keeps and the story reloads), live = the working copy
  local state, phase, _, live = VRFW_STS_Call(VRFW_STS.GET)
  if type(state) ~= "number" then
    return                           -- no save part with the story-complete start
  end
  if state ~= 1 then
    return
  end
  local slot = VRFW_STS_Call(VRFW_STS.GET_SLOT)
  if type(slot) ~= "number" or slot < 1 then
    return                           -- (the save part answers «pending» only for a player slot but the locked one)
  end
  if VRFW_STS_Call(VRFW_STS.GET_BIT, VRFW_STS.FLAG_AVATAR) ~= true then
    VRFW_STS_Log("pending on slot", slot, "but the avatar is not created yet: later")
    return
  end
  if type(phase) ~= "number" then
    return
  end
  local target = SS_DATA.PHASE[1] * 10000 + SS_DATA.PHASE[2]
  local clear = VRFW_STS_Call(VRFW_STS.GET_BIT, VRFW_STS.FLAG_STORY_CLEAR) == true
  -- the four cases (story_start::title_action, story-complete-start.md §11):
  --   b0:1 off, phase 0       -> the whole apply, once
  --   b0:1 on,  phase 0       -> repair: an older loader wrote only the live phase record, lost on save / load /
  --                              story entry; everything else is in the save already: only the phase again
  --   b0:1 on,  phase target  -> applied, waiting for the save (autosave asked; the loader marks «done» from the file)
  --   anything else           -> a game with its own story progress (a duplicate…): marker cleared, nothing touched
  local mode
  if not clear and phase == 0 then
    mode = "apply"
  elseif clear and phase == 0 then
    mode = "repair"
  elseif clear and phase == target then
    VRFW_STS_Log("pending on slot", slot, "already applied in memory (phase", tostring(phase), "live", tostring(live),
                "): waiting for the save")
    if VRFW_STS_Call(VRFW_STS.BUSY) ~= true then
      VRFW_STS_Call(VRFW_STS.AUTO_SAVE)
      VRFW_STS_Log("autosave requested")
    end
    return
  else
    VRFW_STS_Log("pending on slot", slot, "but the story phase is", tostring(phase), "clear", tostring(clear),
                ": marker cleared, nothing applied")
    VRFW_STS_Call(VRFW_STS.SET, slot, 0)
    return
  end
  if VRFW_STS_Call(VRFW_STS.BEGIN) ~= true then
    VRFW_STS_Log("BEGIN refused: nothing applied")
    return
  end
  local ok, err
  if mode == "apply" then
    VRFW_STS_Log("APPLY slot", slot, "data version", SS_DATA.VERSION, "flags", #SS_DATA.BITS, "roster", #SS_DATA.ADDS + #SS_DATA.SCOUTS,
                "normal", #SS_DATA.NORMAL, "trophies", #SS_DATA.TROPHIES)
    ok, err = pcall(VRFW_STS_Apply)
  else
    VRFW_STS_Log("REPAIR slot", slot, ": story clear set but the saved phase is 0 (live", tostring(live),
                "): phase only, nothing else re-applied")
    local old, new = VRFW_STS_Call(VRFW_STS.PHASE, SS_DATA.PHASE[1], SS_DATA.PHASE[2])
    VRFW_STS_Log("phase", tostring(old), "->", tostring(new))
    ok = new == target
    err = ok and nil or "phase write refused"
  end
  local blocked = VRFW_STS_Call(VRFW_STS.END_)
  VRFW_STS_Log(mode == "apply" and "APPLY done" or "REPAIR done", ok and "ok" or ("ERROR " .. tostring(err)),
              "Steam requests dropped", tostring(blocked))
  if VRFW_STS_Call(VRFW_STS.BUSY) ~= true then
    VRFW_STS_Call(VRFW_STS.AUTO_SAVE)            -- CMND_SYSTEM_AUTO_SAVE; the marker turns «done» once it is on disk
    VRFW_STS_Log("autosave requested")
  else
    VRFW_STS_Log("save job busy: the post-story state is saved with the next autosave")
  end
end

-- Wrap OnInit when the menu chunk defines it (same technique as the save_slots block of the same include; any previous
-- __newindex is kept): COMMIT first here too (a second COMMIT is a no-op), so the chain stays save_slots commit ->
-- this apply -> the menu's own OnInit. title_menu_2 ships as lua_patches whose OnInit is defined again after the chunk
-- (no __newindex then): there the host handler of ss_title2.lua runs the apply.
do
  local mt = getmetatable(_G)
  if mt == nil then
    mt = {}
    setmetatable(_G, mt)
  end
  local prev = mt.__newindex
  mt.__newindex = function(t, k, v)
    if k == "OnInit" and type(v) == "function" then
      local menuInit = v
      v = function(...)
        if type(VRFW_SS_CommitPending) == "function" then
          pcall(VRFW_SS_CommitPending)
        end
        pcall(VRFW_STS_OnTitle)
        return menuInit(...)
      end
    end
    if prev == nil then
      rawset(t, k, v)
    elseif type(prev) == "function" then
      prev(t, k, v)
    else
      prev[k] = v
    end
  end
end
