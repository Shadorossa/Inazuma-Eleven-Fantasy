-- mods_menu (VR-Framework): the «Mods» button of the title menu (title_menu_2) and the way into the «Mods» screen
-- (vrfw_mods_menu). Own code: handlers of the framework's title_menu_2 host (VRFW_Host, menu part's
-- lua/title_menu_2/000_host.lua), each one passes on to the next (nxt) for anything that
-- is not our button. No engine call at load time: everything below runs from the game's callbacks.
--
-- Two cases, decided by the mods_menu plugin at boot (CMND_VRFW_MM_STATE):
--   1 = the plugin served the title files with ONE MORE LOWER BUTTON, at the end of the lower row, whatever the mods
--       did to the rows (retail: the 4th, right of Información; a mod that freed a retail place: there).
--       The plugin says where: lower position MM.POS, label name instance MM.NAME, the upper button above it and the
--       upper buttons whose «down» goes to it. Every retail table of the title is reached through a global accessor
--       (GetItemListIdx, GetTextureNameItemButton, ...), so hooking them adds the button without touching the tables
--       (and without reading any other mod's tables: the host sits on top of whatever the mods redefined).
--   0 = the plugin did not understand the title row: no button is added (the screen stays reachable from the
--       framework's other entries).
-- Without the plugin (or with an old ModLoader) nothing changes.

local function MM_Crc(s)
  local crc = 0xFFFFFFFF
  for i = 1, #s do
    crc = bit32.bxor(crc, string.byte(s, i))
    for _ = 1, 8 do
      if bit32.band(crc, 1) ~= 0 then
        crc = bit32.bxor(bit32.rshift(crc, 1), 0xEDB88320)
      else
        crc = bit32.rshift(crc, 1)
      end
    end
  end
  return bit32.bxor(crc, 0xFFFFFFFF)
end

local MM = {
  STATE = MM_Crc("CMND_VRFW_MM_STATE"),   -- () -> title (0 none / 1 own button / 2 another mod's row), screen, version,
                                          --    menu (crc32 of the menu the screen is opened as), where the button is,
                                          --    the tile's sprite names
  TEXT = MM_Crc("CMND_VRFW_MM_TEXT"),     -- (name, language code) -> text of the mod's text.toml
  LANG = VRFW_Cmd.GET_LANGUAGE_CODE,                       -- CMND_GET_LANGUAGE_CODE
  MENU = MM_Crc("vrfw_mods_menu"),        -- until the plugin says otherwise (MM_Mode)
  TITLE = 3874253475,                     -- title_menu_2
  CURSOR = 24113234,                      -- cmn05_01_coursor
  L_LOWER = 3873872512,                   -- title00_07_item_button_lower
  POS = 3,                                -- its lower position (CMND_VRFW_MM_STATE 5th value; 3 = retail 4th button)
  NAME = 11,                              -- its label's name instance (6th value; 11 = retail)
  ABOVE = 6,                              -- the upper button «up» goes to (7th value)
  DOWN = {[6] = true, [7] = true},        -- upper buttons whose «down» comes here (8th value "6,7")
  IDX = 40,                               -- its item list index (retail uses 1..11, mods up to ~14)
  ID = MM_Crc("vrfw_title_menu_mods_item"),
  -- own tile (puzzle piece over the storage shed): sprites the framework's image part adds to title00_07.g4tx
  -- (this part's images\menu\50_title\title00\title00_07.toml, generated by framework_pack / mods_tile_sketches.py)
  -- crc32 of the names by kind (1 focused base, 2 unfocused base, 3 icon), handed over by CMND_VRFW_MM_STATE (9th
  -- value) from the part's tile.toml, the file the sprites are rendered from too. Empty = blank tile.
  SPRITES = {},
  GAIJI_1P = 3337686268,                  -- «1 player» mark after the label, like Opciones
  EXPLAIN = 499981750,                    -- _text_explain01 of the flavour balloon
  LOG = MM_Crc("CMND_EVT_LOG"),
}

local mm_mode = nil         -- nil = not asked yet; 0 off; 1 own button
local mm_co = nil           -- the coroutine that opens the screen and waits

local function MM_Call(cmd, ...)
  local r = table.pack(pcall(funcLuaCommand, cmd, ...))
  if not r[1] then
    return nil
  end
  return table.unpack(r, 2, r.n)
end

local function MM_Mode()
  if mm_mode == nil then
    local title, screen, _, menu, pos, name, above, down, tile = MM_Call(MM.STATE)
    if type(tile) == "string" then
      local k = 0
      for n in string.gmatch(tile .. ",", "([^,]*),") do
        k = k + 1
        MM.SPRITES[k] = n ~= "" and MM_Crc(n) or nil
      end
    end
    if type(pos) == "number" and type(name) == "number" and name > 0 then
      MM.POS, MM.NAME = pos, name
      if type(above) == "number" then
        MM.ABOVE = above
      end
      if type(down) == "string" then
        MM.DOWN = {}
        for d in string.gmatch(down, "%d+") do
          MM.DOWN[tonumber(d)] = true
        end
      end
    end
    -- the menu the screen is opened as: our own row, or the row of another mod's «Mods» screen when the plugin does
    -- not serve the menu registry ([screen] serve_registry)
    if type(menu) == "number" and menu ~= 0 then
      MM.MENU = menu
    end
    if screen ~= true then
      mm_mode = 0
    elseif title == 1 then
      mm_mode = 1
    else
      mm_mode = 0
    end
  end
  return mm_mode
end

-- our lower button exists (the row was served with it and the layer has its instance)
local function MM_Own()
  return MM_Mode() == 1 and type(GetItemButtonNum) == "function" and GetItemButtonNum(false) > MM.POS
end

local function MM_IsOurs(idx, upper)
  return upper ~= true and idx == MM.POS and MM_Own()
end

local function MM_Text(name)
  local s = MM_Call(MM.TEXT, name, MM_Call(MM.LANG) or 1)
  if type(s) ~= "string" or s == "" then
    return name == "title_button" and "Mods" or ""
  end
  return s
end

-- ---- the way into the screen -----------------------------------------------------------------------------------------
local function MM_Coroutine()
  MM_Mode()                                                     -- MM.MENU from the plugin
  funcLuaMenuCommand(1558704558, MM.TITLE, false)               -- title input off
  funcLuaMenuCommand(VRFW_Cmd.SET_LAYER_VISIBLE, MM.CURSOR, 0, false)            -- CMND_SET_LAYER_VISIBLE: cursor
  coroutine.yield()
  funcLuaCommand(VRFW_Cmd.OPEN_MENU_OBJECT, MM.MENU)                            -- CMND_OPEN_MENU_OBJECT
  funcLuaCommand(2039986631, false)
  coroutine.yield()
  while funcLuaMenuCommand(VRFW_Cmd.IS_EXIST_MENU_OBJECT, MM.MENU) do              -- CMND_IS_EXIST_MENU_OBJECT
    coroutine.yield()
  end
  funcLuaCommand(2039986631, true)
  funcLuaMenuCommand(VRFW_Cmd.SET_LAYER_VISIBLE, MM.CURSOR, 0, true)
  funcLuaMenuCommand(1558704558, MM.TITLE, true)
  mm_co = nil
end

function VRFW_MM_OpenScreen()
  if mm_co ~= nil then
    return 1
  end
  funcLuaCommand(VRFW_Cmd.SND_PLAY_SE, 766561556)                         -- sy0080
  mm_co = coroutine.create(MM_Coroutine)
end

local function MM_Busy()
  return mm_co ~= nil
end

-- ---- handlers of the framework's title_menu_2 host -------------------------------------
-- Every handler has the id "mods_menu.title_button" (other mods order against it: after = "mods_menu.title_button").
-- `around` handlers answer for our button and pass everything else on (nxt); the order of the old wrappers is kept.
local T, ID = "title_menu_2", "mods_menu.title_button"

local function on(point, phase, fn)
  if type(_ENV[point]) == "function" then         -- only what this title defines (as the old wrappers did)
    VRFW_Host.on(T, point, { id = ID, phase = phase, fn = fn })
  end
end

if VRFW_Host ~= nil and type(GetItemListIdx) == "function" and type(OnEnter) == "function" and type(Step) == "function" then
  on("GetItemListIdx", "around", function(nxt, a1, a2)
    if MM_IsOurs(a1, a2) then
      return MM.IDX
    end
    return nxt(a1, a2)
  end)

  on("IsEnableMenuItemButton", "around", function(nxt, a1, a2)
    if MM_IsOurs(a1, a2) then
      return true
    end
    return nxt(a1, a2)
  end)

  on("GetTextureNameItemButton", "around", function(nxt, a1, a2, a3)
    if MM_IsOurs(a1, a3) then
      return MM.SPRITES[a2] or 0
    end
    return nxt(a1, a2, a3)
  end)

  -- a1 = name instance (upper 0..n-1, then the lower ones), a2 = upper
  on("GetTextItemName", "around", function(nxt, a1, a2)
    if a2 ~= true and MM_Own() and a1 == MM.NAME then
      local s = MM_Text("title_button")
      local g = funcLuaCommand(VRFW_Cmd.TEXT_GET, MM.GAIJI_1P)          -- CMND_TEXT_GET
      if type(g) == "string" and g ~= "" then
        s = s .. "  " .. g
      end
      return s
    end
    return nxt(a1, a2)
  end)

  on("GetTextNameItemName", "around", function(nxt, a1, a2)
    if MM_IsOurs(a1, a2) then
      return 0
    end
    return nxt(a1, a2)
  end)

  on("GetPlayableModeGaiji", "around", function(nxt, a1, a2)
    if MM_IsOurs(a1, a2) then
      return MM.GAIJI_1P
    end
    return nxt(a1, a2)
  end)

  on("GetTitleMenuItemId", "around", function(nxt, a1, a2)
    if MM_IsOurs(a1, a2) then
      return MM.ID
    end
    return nxt(a1, a2)
  end)

  -- no slide animation for «Mods» (the last lower button: nothing right of it to slide)
  on("GetOffsetAnimeItemAttachLocator", "around", function(nxt, a1, a2)
    if MM_IsOurs(a1, a2) then
      return 0
    end
    return nxt(a1, a2)
  end)

  on("GetLayerNameFromItemListIdx", "around", function(nxt, a1)
    if a1 == MM.IDX and MM_Own() then
      return MM.L_LOWER
    end
    return nxt(a1)
  end)

  on("GetLayerIndexFromItemListIdx", "around", function(nxt, a1)
    if a1 == MM.IDX and MM_Own() then
      return MM.POS
    end
    return nxt(a1)
  end)

  -- up from «Mods» -> the upper button above it; down from the upper buttons at or right of it -> «Mods» (the plugin
  -- measured both on the served layout)
  on("GetItemButtonNextFocusIdx", "around", function(nxt, a1, a2)
    if MM_Own() then
      if a2 == true and a1 == MM.POS then
        local nu = GetItemButtonNum(true)
        return math.max(0, math.min(MM.ABOVE, nu - 1))
      elseif a2 ~= true and MM.DOWN[a1] then
        return MM.POS
      end
    end
    return nxt(a1, a2)
  end)

  on("SetFlavorBalloonText", "around", function(nxt)
    if MM_Own() and GetSelectItemLayerName and GetSelectItemLayerName() == MM.L_LOWER and GetSelectItemIdx() == MM.POS then
      local s = MM_Text("title_flavor")
      if s ~= "" and GetCurrentVisibleFlavorLayer then
        funcLuaMenuCommand(VRFW_Cmd.SET_MENU_TEXT_STRING, GetCurrentVisibleFlavorLayer(), MM.EXPLAIN, s, 0)
      end
      return
    end
    return nxt()
  end)

  on("OnEnter", "around", function(nxt, a1, a2)
    if MM_Busy() then
      return 1
    end
    if a1 == MM.L_LOWER and MM_IsOurs(a2, false) then
      return VRFW_MM_OpenScreen()
    end
    return nxt(a1, a2)
  end)

  on("OnBack", "around", function(nxt, a1)
    if MM_Busy() then
      return 1
    end
    return nxt(a1)
  end)

  on("OnFunction", "around", function(nxt, a1, a2)
    if MM_Busy() then
      return
    end
    return nxt(a1, a2)
  end)

  -- after the title's own Step: one step of the screen's coroutine
  on("Step", "after", function()
    if mm_co ~= nil then
      local ok, err = coroutine.resume(mm_co)
      if not ok then
        MM_Call(MM.LOG, "mods_menu", "title coroutine", tostring(err))
        mm_co = nil
        funcLuaMenuCommand(VRFW_Cmd.SET_LAYER_VISIBLE, MM.CURSOR, 0, true)
        funcLuaMenuCommand(1558704558, MM.TITLE, true)
      end
    end
  end)
end

