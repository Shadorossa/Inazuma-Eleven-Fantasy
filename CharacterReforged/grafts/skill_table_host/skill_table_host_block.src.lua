-- ===== EVT skill_table_host BEGIN =====
-- Character Reforged › the skill table's EXTENSION POINT (docs/framework/skill-table-host.md). Other mods add to this
-- screen (evt_skill_slot_menu, the «Fantasy» 6 + 2 view; script = graft ss2_menus, shipped whole) without a text graft
-- into it: they DECLARE what they add as data and give a Lua function of their own (a [[hooks]] file of this stem, or a
-- lua\_all file), and this block calls it.
--   [[entry]] host = "character_reforged.skill_table.row_action"     a key on the focused move row (the screen's
--     id = "<id>", text = "<guide text row>",                         CMD_FUNC1); the first entry whose function says
--     action = { lua = "<Prefix>.<Function>" }                        «available» takes the key and the guide entry
--   [[entry]] host = "character_reforged.skill_table.x_action"       the same on X (CMD_FUNC4; 2026-10-14: Utilities'
--     (same fields)                                                  partner picker of combination moves); not taken
--                                                                     while Inazuma Fantasy's own block (EVT_CPK) is here
--   [[entry]] host = "character_reforged.skill_table.footer_button"  the button between «Set de jugador» and «Pasiva
--     id = "<id>", text = "<label text row>",                        personalizada» (layer evt_cmn03_07_btn_train,
--     action = { lua = "<Prefix>.<Function>" }                        content\menus\skill_table.toml): ONE slot, the
--                                                                     first entry gets it (the others are logged)
-- The function is called as f(phase, ctx) (pcall'd, except «press», which runs as the screen's action coroutine):
--   row_action / x_action: "available" -> true to take the key on this row; "guide" -> false to leave the guide entry out
--                  (anything else shows it); "press" -> the action (it may yield: SkillTable.Confirm /
--                  SkillTable.Message wait for the window)
--   footer_button: "guide" -> the guide line text (a string, nil = the screen's own); "press" -> the action
--   ctx = {key = "<mod>.<id>", chara = the shown player's charaStHdl, row = focused row (0 = the aura / mix row, 1-6 the
--          moves; nil on the button), slot = the same row, move = the row's move id (0 = empty)}
-- For screen modes (a mod that turns the screen into its own mode, Player Training's training): SkillTable.L (the chunk's
-- locals by name), SkillTable.Env(globals) (an _ENV that resolves the chunk's locals first, then the globals: the code of
-- a block that used to be appended here runs unchanged in a hook file), and the VR-Framework host
-- «evt_skill_slot_menu» (VRFW_Host.on handlers, graft skill_table_host's hook file).
-- One copy per VM (the script is a new file: Character Reforged's or Inazuma Fantasy's merged build, never both); the
-- copy guard below still keeps an earlier copy's wrappers passing straight through. No engine call at chunk load; no
-- new main-chunk local (the chunk is near Lua's 200-locals limit).
CharacterReforged = type(CharacterReforged) == "table" and CharacterReforged or {}
CharacterReforged.SkillTableCopies = (CharacterReforged.SkillTableCopies or 0) + 1
CharacterReforged.SkillTable = {
  COPY = CharacterReforged.SkillTableCopies,
  ROW_HOST = "character_reforged.skill_table.row_action",
  X_HOST = "character_reforged.skill_table.x_action",
  BUTTON_HOST = "character_reforged.skill_table.footer_button",
  BUTTON_LAYER = @crc:evt_cmn03_07_btn_train@,
  ROW_KEY_FUNCTION = 3918588344,                  -- OnFunction id of CMD_FUNC1 on this screen
  X_KEY_FUNCTION = 1141890006,                    -- OnFunction id of CMD_FUNC4 (X) on this screen
  GUIDE_LINE_LAYER = 3078308064,                  -- mainmenu90_05_content_guide_line01
  GUIDE_LINE_NODE = 378156699,                    -- _text_guide01
  BUTTON_LABEL_NODE = 625330766,                  -- _text_cmd01
  BUTTON_KEY_NODE = 950238781,                    -- _text_btn01 (no key glyph: no key is bound)
  TEXT_GET = 4074371074,                          -- CMND_TEXT_GET (text id) -> string
  MSG_KIND = 2351835063, MSG_RESULT = 1523741473, -- general window: Sí / No, its answer
  entries = nil,                                  -- [host] = the declared entries (read once per screen open)
  logged = {},
}
-- the chunk's locals by name (GENERATED by research/grafts/skill_table_host/gen_block.py from the top-level locals of
-- research/grafts/ss2_menus/evt_skill_slot_menu.lua; re-run it after that file declares or drops a local)
CharacterReforged.SkillTable.get = {
@LOCALS_GET@
}
CharacterReforged.SkillTable.set = {
@LOCALS_SET@
}
do
  local SkillTable = CharacterReforged.SkillTable

  function SkillTable.Current()
    return CharacterReforged.SkillTable == SkillTable
  end

  function SkillTable.Log(...)
    local parts = {}
    for k = 1, select("#", ...) do
      parts[#parts + 1] = tostring((select(k, ...)))
    end
    pcall(funcLuaCommand, C.EVT_LOG, "character_reforged skill_table", table.concat(parts, " "))
  end

  -- the chunk's locals: L.n, L.evt_co = ... (a name the chunk does not declare reads nil and cannot be written)
  SkillTable.L = setmetatable({}, {
    __index = function(_, name)
      local getter = SkillTable.get[name]
      if getter ~= nil then
        return getter()
      end
      return nil
    end,
    __newindex = function(_, name, value)
      local setter = SkillTable.set[name]
      if setter == nil then
        error("CharacterReforged.SkillTable.L: the screen has no local " .. tostring(name), 2)
      end
      setter(value)
    end,
  })

  -- an _ENV for code written as if it were appended to this chunk: the chunk's locals first, then `globals`
  function SkillTable.Env(globals)
    return setmetatable({}, {
      __index = function(_, name)
        local getter = SkillTable.get[name]
        if getter ~= nil then
          return getter()
        end
        return globals[name]
      end,
      __newindex = function(_, name, value)
        local setter = SkillTable.set[name]
        if setter ~= nil then
          setter(value)
        else
          globals[name] = value
        end
      end,
    })
  end

  function SkillTable.Text(id)
    local ok, s = pcall(funcLuaCommand, SkillTable.TEXT_GET, id)
    return (ok and type(s) == "string") and s or ""
  end

  -- the text id of a text row name (an entry's `text`); 0 = none
  function SkillTable.TextId(name)
    if type(name) == "number" then
      return name
    end
    if type(name) ~= "string" or name == "" or type(CRC32) ~= "function" then
      return 0
    end
    local ok, id = pcall(CRC32, name)
    return (ok and type(id) == "number") and id or 0
  end

  -- a global function by its path "A.B.C" (resolved at every call: the mods' files may load after this chunk)
  function SkillTable.Resolve(path)
    local value = _ENV
    for part in string.gmatch(path or "", "[^%.]+") do
      if type(value) ~= "table" then
        return nil
      end
      value = rawget(value, part)
    end
    return type(value) == "function" and value or nil
  end

  -- the declared entries of one host, in order: {key, text, path}
  function SkillTable.Entries(host)
    SkillTable.entries = SkillTable.entries or {}
    local cached = SkillTable.entries[host]
    if cached ~= nil then
      return cached
    end
    local out = {}
    local menu = rawget(_ENV, "VRFW_Menu")
    if type(menu) == "table" and type(menu.entries) == "function" then
      local ok, list = pcall(menu.entries, host)
      if ok and type(list) == "table" then
        for _, e in ipairs(list) do
          if e.kind == "lua" and type(e.value) == "string" and e.value ~= "" then
            out[#out + 1] = {key = e.key or e.value, text = e.text, path = e.value}
          end
        end
      end
    end
    SkillTable.entries[host] = out
    if #out > 0 then
      local keys = {}
      for _, e in ipairs(out) do
        keys[#keys + 1] = e.key
      end
      SkillTable.Log("host", host, "entries", table.concat(keys, ", "))
    end
    return out
  end

  function SkillTable.LogOnce(what, ...)
    if not SkillTable.logged[what] then
      SkillTable.logged[what] = true
      SkillTable.Log(what, ...)
    end
  end

  -- f(phase, ctx) of an entry, protected; nil when its function is missing or failed
  function SkillTable.Call(entry, phase, ctx)
    local fn = SkillTable.Resolve(entry.path)
    if fn == nil then
      SkillTable.LogOnce("missing " .. entry.path, "entry", entry.key, "function", entry.path, "is not defined in this menu")
      return nil
    end
    local ok, answer = pcall(fn, phase, ctx)
    if not ok then
      SkillTable.LogOnce("failed " .. entry.key .. " " .. phase, "entry", entry.key, phase, "failed:", tostring(answer))
      return nil
    end
    return answer
  end

  -- ---- helpers for the entries' functions -------------------------------------------------------------------------
  function SkillTable.Chara()
    return n
  end

  function SkillTable.MoveName(skill)
    return EVT_Name(skill)
  end

  -- a message window (inside «press»: it waits until it closes)
  function SkillTable.Message(text)
    EVT_Message(text)
  end

  -- a Sí / No window (inside «press»): true = Sí
  function SkillTable.Confirm(text)
    if PL.MxUnblack ~= nil then
      pcall(PL.MxUnblack)
    end
    funcLuaCommand(C.MSG_OPEN, text, 0, 0, 0, 0, 0, false)
    funcLuaCommand(SkillTable.MSG_KIND, 2, 0)
    coroutine.yield()
    local answer = -1
    while answer == nil or answer < 0 do
      answer = funcLuaCommand(SkillTable.MSG_RESULT)
      coroutine.yield()
    end
    while not funcLuaCommand(C.MSG_DONE) do
      coroutine.yield()
    end
    return answer == 0
  end

  -- "ok" / "decide" / "back" / "refused" / "remove"
  function SkillTable.Sound(kind)
    local id = ({ok = SE_OK, decide = SE_DECIDE, back = SE_BACK, refused = SE_NG, remove = SE_REMOVE})[kind]
    if id ~= nil then
      pcall(funcLuaCommand, C.SE, id)
    end
  end

  -- the rows, the player card, the radar and the guide after a change of the shown player's moves
  function SkillTable.Refresh()
    pcall(EVT_AfterChange)
  end

  -- ---- row actions ------------------------------------------------------------------------------------------------
  -- the focused move row: row (0 aura / mix row, 1-6 moves), move (0 = empty); nil on the buttons / a locked row
  function SkillTable.FocusedRow()
    if n14 == L_BTN then
      return nil
    end
    local row = funcLuaMenuCommand(C.FOCUS_IDX, L_ROW)
    if row == nil or row < 0 or row >= EVT_ROW_NUM or EVT_IsLocked(row) then
      return nil
    end
    return row, EVT_U32(PL.RowMove(row) or 0)
  end

  function SkillTable.RowContext(entry)
    local row, move = SkillTable.FocusedRow()
    if row == nil then
      return nil
    end
    return {key = entry.key, chara = n, row = row, slot = row, move = move}
  end

  -- the first action of `host` (default: the row actions) available on the focused row: entry, ctx
  function SkillTable.RowAction(host)
    host = host or SkillTable.ROW_HOST
    if host == SkillTable.X_HOST and rawget(_ENV, "EVT_CPK") ~= nil then
      return nil                                   -- Inazuma Fantasy's own X (its partner picker) answers alone
    end
    for _, entry in ipairs(SkillTable.Entries(host)) do
      local ctx = SkillTable.RowContext(entry)
      if ctx == nil then
        return nil
      end
      if SkillTable.Call(entry, "available", ctx) == true then
        return entry, ctx
      end
    end
    return nil
  end

  SkillTable.PreviousOnFunction = OnFunction
  function OnFunction(a1, a2)
    local host = (a1 == SkillTable.ROW_KEY_FUNCTION and SkillTable.ROW_HOST)
      or (a1 == SkillTable.X_KEY_FUNCTION and SkillTable.X_HOST) or nil
    if SkillTable.Current() and host ~= nil and evt_co == nil then
      local entry, ctx = SkillTable.RowAction(host)
      if entry ~= nil then
        local fn = SkillTable.Resolve(entry.path)
        SkillTable.Log(host == SkillTable.X_HOST and "x action" or "row action", entry.key, "row", ctx.row, "move",
          string.format("%08X", ctx.move))
        evt_co = coroutine.create(function()
          fn("press", ctx)
        end)
        return
      end
    end
    return SkillTable.PreviousOnFunction(a1, a2)
  end

  -- the row guides (PL.RowGuide and the combo partners' guide both call PL.MxGuideAdd): the available row action's
  -- and X action's entries with their keys' glyphs
  function SkillTable.GuideAdd(host, glyph, key, t, i, c, o)
    local ok, entry, ctx = pcall(SkillTable.RowAction, host)
    if not ok or entry == nil or SkillTable.Call(entry, "guide", ctx) == false then
      return
    end
    local text = SkillTable.TextId(entry.text)
    if text == 0 then
      return
    end
    local k = #t + 1
    t[k], i[k], c[k], o[k] = text, glyph, key, 18
  end

  SkillTable.PreviousGuideAdd = PL.MxGuideAdd
  function PL.MxGuideAdd(t, i, c, o)
    if SkillTable.PreviousGuideAdd ~= nil then
      SkillTable.PreviousGuideAdd(t, i, c, o)
    end
    if not SkillTable.Current() then
      return
    end
    SkillTable.GuideAdd(SkillTable.ROW_HOST, PL.I_FUNC1, PL.K_FUNC1, t, i, c, o)
    SkillTable.GuideAdd(SkillTable.X_HOST, PL.I_FUNC4, PL.K_FUNC4, t, i, c, o)
  end

  -- ---- the footer button -------------------------------------------------------------------------------------------
  function SkillTable.Button()
    local list = SkillTable.Entries(SkillTable.BUTTON_HOST)
    if #list > 1 then
      local others = {}
      for k = 2, #list do
        others[#others + 1] = list[k].key
      end
      SkillTable.LogOnce("button room", "footer button: one slot,", list[1].key, "has it;", table.concat(others, ", "),
        "not shown")
    end
    return list[1]
  end

  function SkillTable.ButtonContext(entry)
    return {key = entry.key, chara = n}
  end

  -- the button's label (the entry's text) and, while it has the focus, the guide line its function gives
  function SkillTable.ButtonRefresh()
    local entry = SkillTable.Button()
    local layer = SkillTable.BUTTON_LAYER
    if entry == nil then
      funcLuaMenuCommand(C.LAYER_VISIBLE, layer, 0, false)
      return
    end
    funcLuaMenuCommand(C.TEXT, layer, SkillTable.BUTTON_LABEL_NODE, SkillTable.Text(SkillTable.TextId(entry.text)), 0)
    funcLuaMenuCommand(C.TEXT, layer, SkillTable.BUTTON_KEY_NODE, "", 0)
    if evt_focus_layer == layer then
      local line = SkillTable.Call(entry, "guide", SkillTable.ButtonContext(entry))
      if type(line) == "string" then
        funcLuaMenuCommand(C.TEXT, SkillTable.GUIDE_LINE_LAYER, SkillTable.GUIDE_LINE_NODE, line, 0)
      end
    end
  end

  SkillTable.PreviousSetupLayer = OnSetupLayer
  function OnSetupLayer(a1, a2, ...)
    if a1 == SkillTable.BUTTON_LAYER and SkillTable.Current() then
      pcall(SkillTable.ButtonRefresh)
      funcLuaMenuCommand(1774843228 --[[CMND_SET_LAYER_ATTACH_LOCATOR_TRACE?]], a1, a2, 3313461902 --[[cursor]], false)
      return
    end
    return SkillTable.PreviousSetupLayer(a1, a2, ...)
  end

  SkillTable.PreviousOpenLayer = OnOpenLayer
  function OnOpenLayer(a1, a2, ...)
    if a1 == SkillTable.BUTTON_LAYER and SkillTable.Current() then
      funcLuaMenuCommand(3781155141 --[[CMND_PLAY_ANIME_TYPE]], a1, a2, 2734777837 --[[Focus]], 2, 973515837 --[[button]])
      pcall(SkillTable.ButtonRefresh)
      return
    end
    return SkillTable.PreviousOpenLayer(a1, a2, ...)
  end

  SkillTable.PreviousChangeFocus = OnChangeFocus
  function OnChangeFocus(a1, a2, ...)
    if a1 == SkillTable.BUTTON_LAYER and SkillTable.Current() then
      evt_focus_layer = a1
      n14 = L_BTN                                    -- the screen treats it like the bottom button (no row info)
      pcall(UpdateEquipItemInfo)
      pcall(SkillTable.ButtonRefresh)
      return
    end
    return SkillTable.PreviousChangeFocus(a1, a2, ...)
  end

  SkillTable.PreviousDecideFocus = OnDecideFocus
  function OnDecideFocus(a1, a2, ...)
    if a1 == SkillTable.BUTTON_LAYER and SkillTable.Current() then
      local entry = SkillTable.Button()
      if entry ~= nil and evt_co == nil then
        local fn = SkillTable.Resolve(entry.path)
        if fn == nil then
          SkillTable.Sound("refused")
          SkillTable.LogOnce("missing " .. entry.path, "entry", entry.key, "function", entry.path, "is not defined in this menu")
          return
        end
        local ctx = SkillTable.ButtonContext(entry)
        SkillTable.Log("footer button", entry.key, "pressed", "chara", tostring(n))
        evt_co = coroutine.create(function()
          fn("press", ctx)
        end)
      end
      return
    end
    return SkillTable.PreviousDecideFocus(a1, a2, ...)
  end

  -- the list popups (sets, role, custom passive) cover the bottom buttons: the declared button too
  if PL ~= nil and PL.ListCover ~= nil then
    SkillTable.PreviousListCover = PL.ListCover
    function PL.ListCover(show, ...)
      local result = SkillTable.PreviousListCover(show, ...)
      if SkillTable.Current() then
        funcLuaMenuCommand(C.LAYER_VISIBLE, SkillTable.BUTTON_LAYER, 0, (not show) and SkillTable.Button() ~= nil)
      end
      return result
    end
  end

  -- a new visit of the screen reads the declarations again
  SkillTable.PreviousInit = OnInit
  function OnInit(...)
    if SkillTable.Current() then
      SkillTable.entries = nil
    end
    return SkillTable.PreviousInit(...)
  end
end
